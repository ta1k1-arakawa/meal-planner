def migration():
    lines = [
        '-- Generated by scripts/generate-seed.py. Do not change deployed migrations 0001-0003.',
        'ALTER TABLE ingredients ADD COLUMN inventory_exempt INTEGER NOT NULL DEFAULT 0 CHECK(inventory_exempt IN (0,1));',
        'UPDATE ingredients SET inventory_exempt=1 WHERE id IN (' + ','.join(q(i) for i in EXEMPT) + ');',
        '-- Existing stocks, movements, shopping rows and nutrition snapshots are retained verbatim.',
        "ALTER TABLE meal_log_items ADD COLUMN amount_source TEXT NOT NULL DEFAULT 'actual' CHECK(amount_source IN ('actual','recipe_default'));",
        "CREATE TRIGGER movement_no_exempt_insert BEFORE INSERT ON inventory_movements WHEN (SELECT inventory_exempt FROM ingredients WHERE id=NEW.ingredient_id)=1 BEGIN SELECT RAISE(ABORT,'inventory_exempt'); END;",
    ]
    for protein in PROTEINS:
        for style in STYLES:
            value = json.dumps(instructions(protein, style), ensure_ascii=False)
            lines.append(f'UPDATE recipes SET instructions_json={q(value)} WHERE id={q(protein + "-" + style)};')
    return '\n'.join(lines) + '\n'


